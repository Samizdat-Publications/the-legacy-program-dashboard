"""Did rebuilding from committed source reproduce the committed artifacts?

This is the CI step that catches the one thing nothing else does: someone edits
`research/` and pushes without running the section 3 pipeline, so the board a reader
sees is not the board the sources describe. It has already earned its keep --
`e04b705` did exactly that, and the gate was red on `master` until 29 August.

WHY IT IS A TOOL AND NOT `git diff --quiet`.

Every generated artifact carries a build-date stamp: `"generated":"YYYY-MM-DD"` in
the JSON, and `Generated by tools/merge.py from research/*.json on YYYY-MM-DD.` in
the `.js` headers. That stamp is a function of the CLOCK, not of the sources. So a
plain `git diff` reports a difference whenever CI rebuilds on a different UTC day
from the machine that built the commit -- eleven files, one line each, nothing
actually wrong.

That is not hypothetical. It happened at 00:01 UTC on 30 August 2026, one minute
past midnight, on a commit built the evening before.

`verify.py --idempotent` ALREADY KNOWS. Its comment says so in terms: neutralise the
stamp, because hashing it "makes this check fail for a build that straddles midnight
UTC -- a real, rare, maximally confusing false failure". The knowledge existed in one
half of the gate and had never been carried to the other.

WHY NOT `git diff -I<regex>`, WHICH LOOKS LIKE THE OBVIOUS FIX.

Because it would silently mask every real change to three of these files.
`data/l0-model.json`, `data/l0-layout-model.json` and `data/design-extract.json` are
each a SINGLE LINE. `-I` drops a hunk when every changed line matches the pattern,
and on a one-line file the only changed line always contains the stamp -- so any
edit anywhere in the file would match and be ignored. A check that cannot fail is
the thing this repo keeps writing down.

So the stamp is normalised in BOTH sides and the full bytes are compared. A file that
differs only in its build date passes and is named in the output. A file that differs
anywhere else fails, however close to the stamp the difference sits.

    python3 tools/check_rebuild.py             # on an OTHERWISE-CLEAN tree, after
                                              # running the section 3 pipeline
    python3 tools/check_rebuild.py --self-test # show it rejecting a real change
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Anchored to the stamp's own context, NEVER a bare \d{4}-\d{2}-\d{2}. The board is
# full of real dates -- dateStart, timeline events, every citation -- and normalising
# those would mask the data changes this check exists to catch.
STAMPS = (
    (re.compile(rb'("generated"\s*:\s*")\d{4}-\d{2}-\d{2}(")'), rb'\1<stamped>\2'),
    (re.compile(rb'(Generated by tools/[^\n]{0,80}? on )\d{4}-\d{2}-\d{2}'), rb'\1<stamped>'),
)


def normalise(b):
    for rx, sub in STAMPS:
        b = rx.sub(sub, b)
    return b


def _git(*args):
    return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True)


def changed_files():
    r = _git("diff", "--name-only")
    if r.returncode != 0:
        raise SystemExit("check_rebuild: git diff failed: " + r.stderr.decode()[:300])
    return [p for p in r.stdout.decode().splitlines() if p.strip()]


def compare(paths):
    """(real, stamp_only) — files that genuinely differ, and files that differ only
    in their build date."""
    real, stamp_only = [], []
    for p in paths:
        head = _git("show", "HEAD:" + p)
        if head.returncode != 0:
            # New file, or one deleted from HEAD. Either way it is a real change.
            real.append((p, "not in HEAD"))
            continue
        try:
            with open(os.path.join(ROOT, p), "rb") as fh:
                now = fh.read()
        except OSError as e:
            real.append((p, "unreadable: %s" % e))
            continue
        if normalise(head.stdout) == normalise(now):
            stamp_only.append(p)
        else:
            a, b = normalise(head.stdout), normalise(now)
            # Where they first part company, so the log says something useful about
            # a 15MB file rather than just naming it.
            i = 0
            for i in range(min(len(a), len(b))):
                if a[i] != b[i]:
                    break
            real.append((p, "first differs at byte %d of %d; %+d bytes"
                            % (i, len(a), len(b) - len(a))))
    return real, stamp_only


def main():
    real, stamp_only = compare(changed_files())
    for p in stamp_only:
        print("  ok    %s differs only in its build-date stamp" % p)
    if not real:
        print("committed artifacts match a fresh build"
              + (" (%d file(s) restamped)" % len(stamp_only) if stamp_only else ""))
        return 0
    print("::error::rebuilding from committed source changed tracked files.")
    print("Run the section 3 pipeline in CLAUDE.md and commit the result.")
    for p, why in real:
        print("  FAIL  %s — %s" % (p, why))
    # THE PRECONDITION, said out loud, because the same output means two different
    # things in the two places this runs. CI checks out a clean tree and then builds,
    # so anything that differs IS rebuild drift. A person running it mid-session has
    # hand edits in flight and will see those listed too -- which is not a defect in
    # the board and should not read as one.
    print()
    print("This compares the whole working tree against HEAD. It assumes the tree was")
    print("clean before the pipeline ran, which is true in CI and may not be true for")
    print("you: a file above that you edited by hand is your own uncommitted work, not")
    print("a rebuild that failed to reproduce. Commit or stash, then re-run.")
    return 1


def self_test():
    """Both halves, because this check asserts two opposite things: that a build-date
    difference is NOT a failure, and that anything else IS."""
    ok = True
    a = b'{"generated":"2026-08-29","nodes":[{"id":"x","dateStart":"1947-07-08"}]}'
    b = b'{"generated":"2026-08-30","nodes":[{"id":"x","dateStart":"1947-07-08"}]}'
    c = b'{"generated":"2026-08-30","nodes":[{"id":"y","dateStart":"1947-07-08"}]}'
    d = b'{"generated":"2026-08-30","nodes":[{"id":"x","dateStart":"1948-07-08"}]}'
    hdr_a = b'/* THE PROGRAM\n   Generated by tools/merge.py from research/*.json on 2026-08-29.\n*/\nX'
    hdr_b = b'/* THE PROGRAM\n   Generated by tools/merge.py from research/*.json on 2026-08-30.\n*/\nX'
    hdr_c = b'/* THE PROGRAM\n   Generated by tools/merge.py from research/*.json on 2026-08-30.\n*/\nY'

    cases = [
        ("a build-date difference is not a failure", normalise(a) == normalise(b), True),
        ("a .js header date difference is not a failure",
         normalise(hdr_a) == normalise(hdr_b), True),
        ("REJECTS: a changed id beside the stamp", normalise(b) == normalise(c), False),
        ("REJECTS: a changed date INSIDE the data", normalise(b) == normalise(d), False),
        ("REJECTS: a changed byte after a restamped header",
         normalise(hdr_b) == normalise(hdr_c), False),
    ]
    print("self-test — the stamp is neutral, everything else is not\n")
    for label, got, want in cases:
        good = got is want
        ok &= good
        print("  %s  %s" % ("ok  " if good else "FAIL", label))

    # And the one that matters most: the stamp regex must not touch a real date.
    real_dates = b'{"dateStart":"2026-08-30","when":"2026-08-30"}'
    untouched = normalise(real_dates) == real_dates
    ok &= untouched
    print("  %s  a date that is not a build stamp is left alone"
          % ("ok  " if untouched else "FAIL"))
    print("\n" + ("self-test passed" if ok else "SELF-TEST FAILED"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(self_test() if "--self-test" in sys.argv else main())
