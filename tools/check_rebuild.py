"""Did rebuilding from committed source reproduce the committed artifacts?

This is the CI step that catches the one thing nothing else does: someone edits
`research/` and pushes without running the section 3 pipeline, so the board a reader
sees is not the board the sources describe. It has already earned its keep --
`e04b705` did exactly that, and the gate was red on `master` until 29 August.

WHY IT IS A TOOL AND NOT `git diff --quiet`.

Every generated artifact carries a build-date stamp: `"generated":"YYYY-MM-DD"` in
the JSON, and `Generated by tools/merge.py from research/*.json on YYYY-MM-DD.` in
the `.js` headers. That stamp is a function of the CLOCK, not of the sources. So a
plain `git diff` reports a difference whenever CI rebuilds on a different UTC day
from the machine that built the commit -- eleven files, one line each, nothing
actually wrong.

That is not hypothetical. It happened at 00:01 UTC on 30 August 2026, one minute
past midnight, on a commit built the evening before.

`verify.py --idempotent` ALREADY KNOWS. Its comment says so in terms: neutralise the
stamp, because hashing it "makes this check fail for a build that straddles midnight
UTC -- a real, rare, maximally confusing false failure". The knowledge existed in one
half of the gate and had never been carried to the other.

WHY NOT `git diff -I<regex>`, WHICH LOOKS LIKE THE OBVIOUS FIX.

Because it would silently mask every real change to three of these files.
`data/l0-model.json`, `data/l0-layout-model.json` and `data/design-extract.json` are
each a SINGLE LINE. `-I` drops a hunk when every changed line matches the pattern,
and on a one-line file the only changed line always contains the stamp -- so any
edit anywhere in the file would match and be ignored. A check that cannot fail is
the thing this repo keeps writing down.

So the stamp is normalised in BOTH sides and the full bytes are compared. A file that
differs only in its build date passes and is named in the output. A file that differs
anywhere else fails, however close to the stamp the difference sits.

    python tools/check_rebuild.py              # on an OTHERWISE-CLEAN tree, after
                                              # running python tools/build.py
    python tools/check_rebuild.py --self-test  # show it rejecting a real change
"""

import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Anchored to the stamp's own context, NEVER a bare \d{4}-\d{2}-\d{2}. The board is
# full of real dates -- dateStart, timeline events, every citation -- and normalising
# those would mask the data changes this check exists to catch.
STAMPS = (
    (re.compile(rb'("generated"\s*:\s*")\d{4}-\d{2}-\d{2}(")'), rb'\1<stamped>\2'),
    (re.compile(rb'(Generated by tools/[^\n]{0,80}? on )\d{4}-\d{2}-\d{2}'), rb'\1<stamped>'),
)


def normalise(b):
    # Line endings too: a Windows checkout with core.autocrlf holds CRLF where HEAD
    # holds LF, and git itself treats the two as the same content.
    b = b.replace(b"\r\n", b"\n")
    for rx, sub in STAMPS:
        b = rx.sub(sub, b)
    return b


def _git(*args):
    return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True)


# The artifacts the section 3 pipeline writes. Used only by the no-build guard
# below -- the comparison itself still walks whatever `git diff` reports, so a
# file added to the pipeline later is still compared without being listed here.
BUILT = (
    "data/the-program.json", "data/l0-model.json", "data/l0-layout-model.json",
    "data/design-extract.json", "data/foia-links.json", "research/topics/_proposals.json",
)


def built_since_last_commit():
    """Did the pipeline actually run since the last commit?

    THIS CHECK DOES NOT REBUILD. It compares the working tree against HEAD, which
    means it says exactly nothing on a clean tree -- and "nothing to report" and
    "the rebuild reproduced" print the same sentence. On 30 August 2026 that cost
    a red CI run: the pipeline was run incompletely, the result committed, and
    this tool then run on the resulting clean tree. It printed "committed
    artifacts match a fresh build" over eleven artifacts that a fresh build does
    not reproduce, and the commit message repeated it.

    A check that cannot fail is the thing this repo keeps writing down. So:
    `.git/index` is rewritten by every commit, and the pipeline rewrites every
    file in BUILT. If NONE of them is newer than the index, no build has happened
    since the last commit and there is nothing to compare.

    The three flows this has to separate, all of them real:

      CI                      checkout, then build, then this  -> artifacts newer, passes
      the documented local    build, then this                 -> artifacts newer, passes
      what happened here      build, commit, then this         -> index newer, REFUSED
    """
    idx = os.path.join(ROOT, ".git", "index")
    if not os.path.exists(idx):
        return True          # a worktree or a submodule; do not invent a failure
    t = os.path.getmtime(idx)
    for p in BUILT:
        f = os.path.join(ROOT, p)
        if os.path.exists(f) and os.path.getmtime(f) >= t:
            return True
    return False


# Where a build writes. `--built-only` compares only paths under these, which is
# how tools/gate.py runs it: a person running the gate mid-session has hand edits
# in flight (a note, CLAUDE.md, a tool being changed) and those are not rebuild
# drift. CI runs this WITHOUT the flag, over the whole tree, as a step of its own.
BUILT_PREFIXES = ("data/", "app/public/data/", "app/public/patents/",
                  "research/_remediation.json", "research/topics/_proposals.json")


def is_built(path):
    return path.replace("\\", "/").startswith(BUILT_PREFIXES)


def changed_files():
    # Against HEAD, not against the index. A bare `git diff` compares the working
    # tree with the INDEX, so an artifact that had already been `git add`-ed was
    # never listed and read as matching. The mtime guard usually fired first, but
    # with a message ("nothing was rebuilt") that misdescribed what happened.
    r = _git("diff", "HEAD", "--name-only")
    if r.returncode != 0:
        raise SystemExit("check_rebuild: git diff failed: " + r.stderr.decode()[:300])
    paths = [p for p in r.stdout.decode().splitlines() if p.strip()]
    # And a build output nobody committed. `git diff HEAD` lists only tracked paths,
    # so a file the build newly writes (app/public/data/topics/<id>.json when a topic
    # is added, 25 September 2026) was invisible here: CI would build it, compare
    # nothing, and pass, while the deploy shipped a file master does not hold.
    # Untracked paths under the build's outputs are real drift ("not in HEAD").
    u = _git("ls-files", "--others", "--exclude-standard")
    if u.returncode != 0:
        raise SystemExit("check_rebuild: git ls-files failed: " + u.stderr.decode()[:300])
    paths += [p for p in u.stdout.decode().splitlines() if p.strip() and is_built(p)]
    return paths


def compare(paths):
    """(real, stamp_only) — files that genuinely differ, and files that differ only
    in their build date."""
    real, stamp_only = [], []
    for p in paths:
        head = _git("show", "HEAD:" + p)
        if head.returncode != 0:
            # New file, or one deleted from HEAD. Either way it is a real change.
            real.append((p, "not in HEAD"))
            continue
        try:
            with open(os.path.join(ROOT, p), "rb") as fh:
                now = fh.read()
        except OSError as e:
            real.append((p, "unreadable: %s" % e))
            continue
        if normalise(head.stdout) == normalise(now):
            stamp_only.append(p)
        else:
            a, b = normalise(head.stdout), normalise(now)
            # Where they first part company, so the log says something useful about
            # a 15MB file rather than just naming it.
            i = 0
            for i in range(min(len(a), len(b))):
                if a[i] != b[i]:
                    break
            real.append((p, "first differs at byte %d of %d; %+d bytes"
                            % (i, len(a), len(b) - len(a))))
    return real, stamp_only


def main(built_only=False):
    if not built_since_last_commit():
        print("::error::check_rebuild: nothing was rebuilt, so there is nothing to compare.")
        print("This tool diffs the working tree against HEAD; it does not build. On a")
        print("clean tree with no build behind it, silence means 'you did not run the")
        print("pipeline', not 'the rebuild reproduced'. Run the build, then run this")
        print("again:")
        print()
        print("    python tools/build.py")
        return 1
    paths = changed_files()
    if built_only:
        skipped = [p for p in paths if not is_built(p)]
        paths = [p for p in paths if is_built(p)]
        if skipped:
            print("  (--built-only: %d changed file(s) outside the build's outputs not "
                  "compared)" % len(skipped))
    real, stamp_only = compare(paths)
    for p in stamp_only:
        print("  ok    %s differs only in its build-date stamp" % p)
    if not real:
        print("committed artifacts match a fresh build"
              + (" (%d file(s) restamped)" % len(stamp_only) if stamp_only else ""))
        return 0
    print("::error::rebuilding from committed source changed tracked files.")
    print("Run python tools/build.py and commit the result.")
    for p, why in real:
        print("  FAIL  %s — %s" % (p, why))
    # THE PRECONDITION, said out loud, because the same output means two different
    # things in the two places this runs. CI checks out a clean tree and then builds,
    # so anything that differs IS rebuild drift. A person running it mid-session has
    # hand edits in flight and will see those listed too -- which is not a defect in
    # the board and should not read as one.
    print()
    print("This compares the whole working tree against HEAD. It assumes the tree was")
    print("clean before the pipeline ran, which is true in CI and may not be true for")
    print("you: a file above that you edited by hand is your own uncommitted work, not")
    print("a rebuild that failed to reproduce. Commit or stash, then re-run.")
    return 1


def self_test():
    """Both halves, because this check asserts two opposite things: that a build-date
    difference is NOT a failure, and that anything else IS."""
    ok = True
    a = b'{"generated":"2026-08-29","nodes":[{"id":"x","dateStart":"1947-07-08"}]}'
    b = b'{"generated":"2026-08-30","nodes":[{"id":"x","dateStart":"1947-07-08"}]}'
    c = b'{"generated":"2026-08-30","nodes":[{"id":"y","dateStart":"1947-07-08"}]}'
    d = b'{"generated":"2026-08-30","nodes":[{"id":"x","dateStart":"1948-07-08"}]}'
    hdr_a = b'/* THE PROGRAM\n   Generated by tools/merge.py from research/*.json on 2026-08-29.\n*/\nX'
    hdr_b = b'/* THE PROGRAM\n   Generated by tools/merge.py from research/*.json on 2026-08-30.\n*/\nX'
    hdr_c = b'/* THE PROGRAM\n   Generated by tools/merge.py from research/*.json on 2026-08-30.\n*/\nY'

    cases = [
        ("a build-date difference is not a failure", normalise(a) == normalise(b), True),
        ("a .js header date difference is not a failure",
         normalise(hdr_a) == normalise(hdr_b), True),
        ("REJECTS: a changed id beside the stamp", normalise(b) == normalise(c), False),
        ("REJECTS: a changed date INSIDE the data", normalise(b) == normalise(d), False),
        ("REJECTS: a changed byte after a restamped header",
         normalise(hdr_b) == normalise(hdr_c), False),
        ("a CRLF-only difference is not a failure",
         normalise(hdr_a.replace(b"\n", b"\r\n")) == normalise(hdr_a), True),
        ("REJECTS: a real change hidden behind CRLF",
         normalise(hdr_b.replace(b"\n", b"\r\n")) == normalise(hdr_c), False),
    ]
    print("self-test — the stamp is neutral, everything else is not\n")
    for label, got, want in cases:
        good = got is want
        ok &= good
        print("  %s  %s" % ("ok  " if good else "FAIL", label))

    # And the one that matters most: the stamp regex must not touch a real date.
    real_dates = b'{"dateStart":"2026-08-30","when":"2026-08-30"}'
    untouched = normalise(real_dates) == real_dates
    ok &= untouched
    print("  %s  a date that is not a build stamp is left alone"
          % ("ok  " if untouched else "FAIL"))

    # The no-build guard, poisoned on the real filesystem rather than on a stand-in
    # predicate. CLAUDE.md section 5: poison the page, not just the predicate. Both
    # directions are exercised against actual mtimes on actual BUILT paths.
    import tempfile, time
    # The --built-only filter, both ways: hand edits are out, build outputs are in.
    print("\nself-test - --built-only keeps build outputs and drops hand edits\n")
    for path, want in (("app/public/data/index.json", True), ("data/the-program.json", True),
                       ("research/_remediation.json", True),
                       ("app/public/data/topics.json", True),
                       ("app/public/data/topics/aaro.json", True),
                       ("research/topics/aaro.json", False),
                       ("CLAUDE.md", False), ("notes/STATE.md", False),
                       ("tools/verify.py", False), ("research/w1-legacy.json", False)):
        got = is_built(path)
        good = got is want
        ok &= good
        print("  %s  %s%s" % ("ok  " if good else "FAIL",
                              "" if want else "REJECTS: ", path))

    # A build output nobody committed must be listed, on the real filesystem: an
    # untracked file under a build prefix, and one outside every prefix.
    print("\nself-test - an untracked build output is compared, a stray file is not\n")
    probe_in = os.path.join(ROOT, "app", "public", "data", "topics", "zz-selftest-untracked.json")
    probe_out = os.path.join(ROOT, "notes", "zz-selftest-untracked.md")
    made = []
    try:
        for p in (probe_in, probe_out):
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w") as fh:
                fh.write("{}\n")
            made.append(p)
        listed = changed_files()
        got_in = "app/public/data/topics/zz-selftest-untracked.json" in listed
        got_out = "notes/zz-selftest-untracked.md" in listed
        ok &= got_in and not got_out
        print("  %s  an untracked file under app/public/data/ is listed" % ("ok  " if got_in else "FAIL"))
        print("  %s  REJECTS: an untracked hand file is not listed" % ("ok  " if not got_out else "FAIL"))
    finally:
        for p in made:
            os.remove(p)

    print("\nself-test — the no-build guard, against real mtimes\n")
    idx = os.path.join(ROOT, ".git", "index")
    if not os.path.exists(idx):
        print("  n/a   no .git/index here (worktree or submodule); guard returns True by design")
    else:
        built = [os.path.join(ROOT, p) for p in BUILT if os.path.exists(os.path.join(ROOT, p))]
        if not built:
            print("  FAIL  none of BUILT exists, so the guard can never fire")
            ok = False
        else:
            saved = {f: (os.path.getmtime(f), os.path.getatime(f)) for f in built}
            saved_idx = (os.path.getmtime(idx), os.path.getatime(idx))
            try:
                # ACCEPTS: an artifact newer than the index is a build that happened.
                now = time.time()
                os.utime(idx, (now - 100, now - 100))
                os.utime(built[0], (now, now))
                got = built_since_last_commit()
                ok &= got is True
                print("  %s  a build after the last commit is a comparison worth making"
                      % ("ok  " if got else "FAIL"))
                # REJECTS: every artifact older than the index is a commit with no
                # build behind it -- exactly the 30 August case.
                for f in built:
                    os.utime(f, (now - 200, now - 200))
                os.utime(idx, (now, now))
                got = built_since_last_commit()
                ok &= got is False
                print("  %s  REJECTS: a clean tree with no build behind it"
                      % ("ok  " if got is False else "FAIL"))
            finally:
                for f, (m, a_) in saved.items():
                    os.utime(f, (a_, m))
                os.utime(idx, (saved_idx[1], saved_idx[0]))

    print("\n" + ("self-test passed" if ok else "SELF-TEST FAILED"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(self_test() if "--self-test" in sys.argv
             else main(built_only="--built-only" in sys.argv))
